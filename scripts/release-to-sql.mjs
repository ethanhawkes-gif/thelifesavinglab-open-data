#!/usr/bin/env node
// src/data/release.json -> deterministic INSERTs (seeds/seed.sql) for D1 or SQLite.
import { readFileSync, writeFileSync } from 'node:fs';

export function q(v) { return v === null || v === undefined ? 'NULL' : "'" + String(v).replace(/'/g, "''") + "'"; }

export function releaseToSQL(rel) {
  const m = rel.meta;
  const out = ['-- generated by scripts/release-to-sql.mjs; do not edit', 'BEGIN;'];
  out.push(`INSERT OR REPLACE INTO datasets VALUES (${q(m.dataset_id)},${q(m.title)},${q(m.data_license)},${q(m.version)});`);
  for (const s of rel.sources) out.push(`INSERT OR REPLACE INTO sources (id,citation,access_terms,license) VALUES (${q(s.id)},${q(s.citation)},${q(s.access_terms)},${q(s.license)});`);
  for (const o of rel.observations) out.push(`INSERT OR REPLACE INTO observations (id,dataset_id,label,year,place,toll,cause,confidence,tier,tier_basis,source_id) VALUES (${[o.id, m.dataset_id, o.label, o.year, o.place, o.toll, o.cause, o.confidence, o.tier, o.tier_basis, o.source_id].map(q).join(',')});`);
  for (const p of rel.non_additive) out.push(`INSERT OR REPLACE INTO non_additive_pairs VALUES (${q(p.a_id)},${q(p.b_id)},${q(p.reason)});`);
  out.push(`INSERT OR REPLACE INTO releases VALUES (${q(m.version)},${q(m.dataset_id)},${q(m.released)},${q(rel.manifest.sha256['export.json'])},${q(rel.manifest.sha256['export.csv'])});`);
  for (const o of rel.observations) out.push(`INSERT OR REPLACE INTO lineage VALUES (${q(o.id)},${q(m.version)},'canon-import',NULL);`);
  out.push('COMMIT;');
  return out.join('\n') + '\n';
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync('seeds/seed.sql', releaseToSQL(JSON.parse(readFileSync('src/data/release.json', 'utf8'))));
  console.log('wrote seeds/seed.sql');
}
